/**
 * Extract the best geographic coordinate from a text string by scanning
 * for known geographic entities. Returns the FIRST (most specific) match.
 * Priority: cities > countries > regions
 */
export function extractCoordinates(text: string): [number, number] | null {
  const lower = text.toLowerCase();
  
  // Sort keys by length descending so "south china sea" matches before "china"
  const sortedKeys = Object.keys(GEO_DICTIONARY).sort((a, b) => b.length - a.length);
  
  for (const key of sortedKeys) {
    // Use word boundary check to avoid partial matches (e.g., "used" matching "us ")
    if (lower.includes(key)) {
      return GEO_DICTIONARY[key];
    }
  }
  
  return null;
}
